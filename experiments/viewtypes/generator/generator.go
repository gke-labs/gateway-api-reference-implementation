// GenerateAll runs code generation for all default KindSpecs and writes files into outDir.
func GenerateAll(outDir string) error {
	specs := DefaultSpecs()
	for _, spec := range specs {
		var filename string
		switch spec.Kind {
		case "ConfigMap":
			filename = "configmap_view.go"
		case "Secret":
			filename = "secret_view.go"
		case "HTTPRoute":
			filename = "httproute_view.go"
		default:
			filename = fmt.Sprintf("%s_view.go", spec.Kind)
		}

		code, err := GenerateKind(spec)
		if err != nil {
			return fmt.Errorf("failed to generate %s: %w", spec.Kind, err)
		}

		formatted, err := format.Source(code)
		if err != nil {
			return fmt.Errorf("failed to format generated code for %s: %w", spec.Kind, err)
		}

		if err := os.WriteFile(filepath.Join(outDir, filename), formatted, 0644); err != nil {
			return fmt.Errorf("failed to write %s: %w", filename, err)
		}
	}
	return nil
}

